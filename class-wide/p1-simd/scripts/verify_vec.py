#!/usr/bin/env python3
"""Summarize vectorization evidence per variant/function from objdump + compiler reports.
Writes reports/vec_summary.md. Run after `make`. x86 register-width classes:
xmm=128b, ymm=256b, zmm=512b. 'ss/sd' suffix = scalar, 'ps/pd' = packed."""
import re, glob, os, collections

FUNCS = ["saxpy_f32", "dot_f32", "mul_f32", "stencil_f32", "saxpy_stride_f32",
         "saxpy_gather_f32", "saxpy_f64", "dot_f64", "mul_f64", "stencil_f64",
         "saxpy_stride_f64", "saxpy_gather_f64"]
os.chdir(os.path.join(os.path.dirname(__file__), ".."))

def funcs_from_disasm(path):
    out, cur = {}, None
    for line in open(path):
        m = re.match(r"^[0-9a-f]+ <(\w+)>:", line)
        if m:
            cur = m.group(1); out[cur] = []; continue
        if cur and "\t" in line:
            parts = line.split("\t")
            if len(parts) >= 2:
                out[cur].append(parts[-1].strip() if len(parts) == 2 else "\t".join(parts[1:]).strip())
    return out

def classify(insns):
    c = collections.Counter()
    for ins in insns:
        op = ins.split()[0] if ins.split() else ""
        regs = ins[len(op):]
        if re.search(r"(add|mul|fmadd|fmsub|sub)\w*p[sd]", op): c["packed_fp"] += 1
        if re.search(r"(add|mul|fmadd|fmsub|sub)\w*s[sd]$", op): c["scalar_fp"] += 1
        if "fmadd" in op: c["fma"] += 1
        if "gather" in op: c["gather"] += 1
        if "zmm" in regs: c["zmm"] += 1
        elif "ymm" in regs: c["ymm"] += 1
        elif "xmm" in regs: c["xmm"] += 1
        # NEON (AArch64): v-registers with lane arrangement
        if re.search(r"v\d+\.(4s|2d|8h)", regs): c["neon_vec"] += 1
    return c

lines = ["# Vectorization evidence (auto-generated by scripts/verify_vec.py)\n",
         "Counts are static instruction counts inside each function body "
         "(includes prologue/epilogue code), not dynamic counts.\n"]
for dis in sorted(glob.glob("reports/disasm_*.txt")):
    v = dis.split("disasm_")[1][:-4]
    fs = funcs_from_disasm(dis)
    lines.append(f"\n## {v}\n\n| function | packed FP | scalar FP | FMA | gather | zmm | ymm | xmm | NEON |\n|---|---|---|---|---|---|---|---|---|")
    for f in FUNCS:
        if f not in fs: continue
        c = classify(fs[f])
        lines.append(f"| {f} | {c['packed_fp']} | {c['scalar_fp']} | {c['fma']} | {c['gather']} | "
                     f"{c['zmm']} | {c['ymm']} | {c['xmm']} | {c['neon_vec']} |")
    rep = f"reports/vec_report_{v}.txt"
    if os.path.exists(rep):
        msgs = sorted(set(re.findall(r"kernels\.c:(\d+):\d+: (optimized: loop vectorized using \d+ byte vectors|remark: vectorized loop[^\n]*|missed: couldn't vectorize loop)", open(rep).read())), key=lambda t: int(t[0]))
        if msgs:
            lines.append("\nCompiler report (source line: message):\n")
            lines += [f"- line {l}: {m}" for l, m in msgs]

open("reports/vec_summary.md", "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
