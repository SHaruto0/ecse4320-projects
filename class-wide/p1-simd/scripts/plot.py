#!/usr/bin/env python3
"""Make all figures + processed tables from results/raw/*.csv.
Outputs: figures/*.png, results/processed/*.csv, results/processed/summary.md"""
import json, os, glob
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(ROOT)
os.makedirs("figures", exist_ok=True); os.makedirs("results/processed", exist_ok=True)
M = json.load(open("machine.json"))
plt.rcParams.update({"figure.dpi": 130, "axes.grid": True, "grid.alpha": .3, "font.size": 9})
COL = {"scalar": "#555555", "auto": "#1f77b4", "native": "#2ca02c",
       "native512": "#d62728", "native_fm": "#9467bd"}

def load(name):
    p = f"results/raw/{name}.csv"
    if not os.path.exists(p): return None
    d = pd.read_csv(p)
    keys = ["variant", "kernel", "dtype", "n", "misalign", "stride", "idx"]
    d["rep"] = d.groupby(keys).cumcount()   # which repeat of the sweep (--repeat)
    RAW[name] = d
    # aggregate repeats: median of per-run medians; error bars = min..max across runs
    g = d.groupby(keys, as_index=False).agg(ws_bytes=("ws_bytes", "first"), med_ns=("med_ns", "median"),
        lo_ns=("med_ns", "min"), hi_ns=("med_ns", "max"), best_ns=("min_ns", "min"),
        std_ns=("std_ns", "mean"), runs=("med_ns", "size"), gflops=("gflops", "median"),
        gibps=("gibps", "median"), ns_per_elem=("ns_per_elem", "median"),
        max_err=("max_err", "max"), passed=("pass", "min"))
    g["rel_err"] = np.where(g.runs > 1, (g.hi_ns - g.lo_ns) / 2 / g.med_ns, g.std_ns / g.med_ns)
    g.to_csv(f"results/processed/{name}.csv", index=False)
    return g

RAW = {}
def yerr(val, lo, hi):
    """asymmetric error bars (never negative)"""
    return np.vstack([np.clip(val - lo, 0, None), np.clip(hi - val, 0, None)])

def cache_lines(ax):
    for kib, lab in [(M["l1d_kib"], "L1d"), (M["l2_kib"], "L2"), (M["l3_kib"], "LLC")]:
        ax.axvline(kib * 1024, color="k", ls=":", lw=.8)
        ax.text(kib * 1024, ax.get_ylim()[1], f" {lab}", va="top", fontsize=7)

out = ["# Processed summary (auto-generated by scripts/plot.py)\n"]
b = load("baseline")
if b is not None:
    # speedup computed per repeat (scalar and variant from the same sweep), then median/min/max
    r = RAW["baseline"]
    r = r.merge(r[r.variant == "scalar"][["kernel", "dtype", "n", "rep", "med_ns"]],
                on=["kernel", "dtype", "n", "rep"], suffixes=("", "_sc"))
    r["sp"] = r.med_ns_sc / r.med_ns
    sp = r.groupby(["variant", "kernel", "dtype", "n"]).sp.agg(["median", "min", "max"]).reset_index()
    b = b.merge(sp, on=["variant", "kernel", "dtype", "n"])
    b["speedup"], b["sp_lo"], b["sp_hi"] = b["median"], b["min"], b["max"]
    b["speedup_err"] = (b.sp_hi - b.sp_lo) / 2
    b.to_csv("results/processed/baseline_speedup.csv", index=False)

    # Fig 1: speedup vs working set, per kernel
    fig, axs = plt.subplots(2, 2, figsize=(10, 7), sharex=True)
    for ax, k in zip(axs.flat, ["saxpy", "dot", "mul", "stencil"]):
        for v in ["auto", "native", "native512", "native_fm"]:
            for dt, ls in [("f32", "-"), ("f64", "--")]:
                s = b[(b.kernel == k) & (b.variant == v) & (b.dtype == dt)].sort_values("ws_bytes")
                if len(s): ax.errorbar(s.ws_bytes, s.speedup, yerr=yerr(s.speedup, s.sp_lo, s.sp_hi), color=COL[v], ls=ls,
                                       lw=1.2, capsize=1.5, label=f"{v} {dt}")
        ax.set_xscale("log", base=2); ax.set_title(k); ax.set_ylabel("speedup vs scalar")
        ax.axhline(1, color="k", lw=.6); cache_lines(ax)
    for ax in axs[1]: ax.set_xlabel("working set (bytes)")
    axs[0, 0].legend(fontsize=6, ncol=2)
    fig.suptitle("SIMD speedup over scalar vs working set (solid f32, dashed f64; bars = min..max of 3 runs)")
    fig.tight_layout(); fig.savefig("figures/fig1_speedup_vs_ws.png"); plt.close()

    # Fig 2: locality sweep throughput for saxpy
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.8))
    for dt, ax in zip(["f32", "f64"], axs):
        for v in ["scalar", "auto", "native", "native512"]:
            s = b[(b.kernel == "saxpy") & (b.variant == v) & (b.dtype == dt)].sort_values("ws_bytes")
            if len(s): ax.errorbar(s.ws_bytes, s.gibps, yerr=yerr(s.gibps, s.gibps * s.med_ns / s.hi_ns, s.gibps * s.med_ns / s.lo_ns), color=COL[v], label=v, capsize=1.5)
        ax.set_xscale("log", base=2); ax.set_yscale("log"); ax.set_title(f"saxpy {dt}")
        ax.set_xlabel("working set (bytes)"); ax.set_ylabel("useful GiB/s (12B or 24B/elem)")
        cache_lines(ax); ax.legend(fontsize=7)
    fig.suptitle("Locality sweep: SIMD gains compress once data leaves cache")
    fig.tight_layout(); fig.savefig("figures/fig2_locality_saxpy.png"); plt.close()

    # Fig 6: data type comparison (L1-resident & DRAM-resident)
    def nl1(k, dt):  # largest N whose working set fits in half of L1d, per kernel/dtype
        return b[(b.kernel == k) & (b.dtype == dt) & (b.ws_bytes <= M["l1d_kib"] * 1024 * 0.5)].n.max()
    nD = b.n.max()
    rows = []
    for k in ["saxpy", "dot", "mul", "stencil"]:
        for dt in ["f32", "f64"]:
            for n, reg in [(nl1(k, dt), "L1"), (nD, "DRAM")]:
                for v in ["native", "native512", "native_fm"]:
                    s = b[(b.kernel == k) & (b.dtype == dt) & (b.n == n) & (b.variant == v)]
                    if len(s): rows.append(dict(kernel=k, dtype=dt, region=reg, variant=v,
                                                speedup=s.speedup.iloc[0], gflops=s.gflops.iloc[0],
                                                ns_per_elem=s.ns_per_elem.iloc[0]))
    dtab = pd.DataFrame(rows).assign(n_L1=lambda x: [nl1(k, d) for k, d in zip(x.kernel, x.dtype)]); dtab.to_csv("results/processed/dtype_table.csv", index=False)
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.5))
    for ax, reg in zip(axs, ["L1", "DRAM"]):
        t = dtab[(dtab.region == reg) & (dtab.variant == "native")].pivot(index="kernel", columns="dtype", values="speedup")
        t.plot.bar(ax=ax, color=["#1f77b4", "#ff7f0e"], rot=0)
        ax.set_title(f"native speedup, {reg}-resident"); ax.set_ylabel("speedup vs scalar"); ax.axhline(1, color="k", lw=.6)
    fig.tight_layout(); fig.savefig("figures/fig6_dtype.png"); plt.close()

    # Fig 8: negative case: dot product reduction without fast-math
    fig, ax = plt.subplots(figsize=(6, 3.8))
    for v in ["scalar", "auto", "native", "native_fm"]:
        s = b[(b.kernel == "dot") & (b.variant == v) & (b.dtype == "f32")].sort_values("ws_bytes")
        if len(s): ax.errorbar(s.ws_bytes, s.gflops, yerr=yerr(s.gflops, s.gflops * s.med_ns / s.hi_ns, s.gflops * s.med_ns / s.lo_ns), color=COL[v], label=v, capsize=1.5)
    ax.set_xscale("log", base=2); ax.set_xlabel("working set (bytes)"); ax.set_ylabel("GFLOP/s")
    ax.set_title("dot f32: 'vectorized' per compiler report, but in-order reduction"); cache_lines(ax); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig("figures/fig8_negative_dot.png"); plt.close()

    # Roofline (Fig 7)
    BWL = {"saxpy": 12, "dot": 8, "mul": 12, "stencil": 8}   # useful bytes/elem f32
    FL = {"saxpy": 2, "dot": 2, "mul": 1, "stencil": 5}
    big = b[(b.n == nD) & (b.kernel.isin(["mul", "saxpy"]))]
    bw = big.gibps.max() * 1.073741824  # GB/s, best sustained useful bandwidth at DRAM size, any build
    lanes32 = {v: l for v, l in {"native": 8, "native512": 16}.items() if (b.variant == v).any()}
    fig, ax = plt.subplots(figsize=(6.5, 4.5))
    ai = np.logspace(-2, 1.5, 200)
    for v, lw in lanes32.items():
        peak = M["ghz"] * M["fma_units"] * lw * 2
        ax.plot(ai, np.minimum(peak, bw * ai), color=COL[v], label=f"roof: {lw}-lane f32 FMA peak {peak:.0f} GFLOP/s")
    ax.plot(ai, bw * ai, "k:", lw=.8, label=f"measured DRAM BW {bw:.1f} GB/s")
    rl = []
    for k in BWL:
        for n, reg, mk in [(nl1(k, "f32"), "L1", "o"), (nD, "DRAM", "s")]:
            v = "native_fm" if k == "dot" else "native"
            s = b[(b.kernel == k) & (b.dtype == "f32") & (b.n == n) & (b.variant == v)]
            if not len(s): continue
            x = FL[k] / BWL[k]; y = s.gflops.iloc[0]
            ax.scatter(x, y, marker=mk, s=30, zorder=3)
            ax.annotate(f"{k} {reg}", (x, y), fontsize=7, xytext=(3, 3), textcoords="offset points")
            rl.append(dict(kernel=k, region=reg, AI_flop_per_byte=round(x, 3), gflops=round(y, 2),
                           bw_bound_gflops=round(bw * x, 2), pct_of_bw_roof=round(100 * y / (bw * x), 1)))
    ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlabel("arithmetic intensity (FLOP/byte, f32, no write-allocate)")
    ax.set_ylabel("GFLOP/s"); ax.legend(fontsize=7); ax.set_title("Roofline (f32, native build)")
    fig.tight_layout(); fig.savefig("figures/fig7_roofline.png"); plt.close()
    rlt = pd.DataFrame(rl); rlt.to_csv("results/processed/roofline.csv", index=False)

    keyrows = b[((b.n == nD) | (b.n == b.apply(lambda r: nl1(r.kernel, r.dtype), axis=1))) & (b.variant != "scalar")][["kernel", "dtype", "variant", "n", "gflops", "gibps", "speedup", "speedup_err"]]
    out += [f"Measured DRAM bandwidth (best useful GB/s of mul/saxpy, any build, N={nD}): **{bw:.1f} GB/s**\n",
            "## Speedup at L1-resident vs DRAM-resident N\n", keyrows.round(3).to_markdown(index=False),
            "\n## Roofline points\n", rlt.to_markdown(index=False), "\n## Data type\n", dtab.round(3).to_markdown(index=False)]
    fails = b[b.passed == 0]
    out.append(f"\nCorrectness failures in baseline: {len(fails)}\n")

a = load("align")
if a is not None:
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.5))
    for ax, n in zip(axs, sorted(a.n.unique())):
        for v in ["scalar", "native", "native512"]:
            for dt, ls in [("f32", "-o"), ("f64", "--s")]:
                s = a[(a.n == n) & (a.variant == v) & (a.dtype == dt)].sort_values("misalign")
                if len(s): ax.errorbar(s.misalign * (4 if dt == "f32" else 8), s.ns_per_elem, yerr=yerr(s.ns_per_elem, s.lo_ns / s.n, s.hi_ns / s.n),
                                       fmt=ls, color=COL[v], ms=3, label=f"{v} {dt}", capsize=1.5)
        ax.set_xlabel("start offset from 64B boundary (bytes)"); ax.set_ylabel("ns / element")
        ax.set_title(f"saxpy alignment, N={n}"); ax.legend(fontsize=6)
    fig.tight_layout(); fig.savefig("figures/fig3_alignment.png"); plt.close()
    out += ["\n## Alignment (saxpy)\n", a[["variant", "dtype", "n", "misalign", "ns_per_elem", "rel_err"]].round(4).to_markdown(index=False)]

t = load("tail")
if t is not None:
    # for tiny L1-resident calls the minimum is the least noisy estimator
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.6))
    rows = []
    for v in ["scalar", "auto", "native", "native512"]:
        s_ = t[t.variant == v].sort_values("n")
        if not len(s_): continue
        axs[0].plot(s_.n, s_.best_ns, "-o", ms=2, color=COL[v], label=v)
        p = np.polyfit(s_.n, s_.best_ns, 1)
        res = (s_.best_ns - np.polyval(p, s_.n)).groupby(s_.n % 8).mean()
        axs[1].plot(res.index, res.values, "-o", color=COL[v], label=f"{v} ({p[0]:.3f} ns/elem)")
        rows.append(dict(variant=v, ns_per_elem_slope=round(p[0], 4), resid_range_ns=round(res.max() - res.min(), 2),
                         resid_by_n_mod_8=[float(x) for x in res.round(2).values]))
    axs[0].set_xlabel("N (f32 elements)"); axs[0].set_ylabel("best ns per call"); axs[0].set_yscale("log")
    axs[0].set_title("saxpy f32, N = 1024..1088 (L1)"); axs[0].legend(fontsize=7)
    axs[1].set_xlabel("N mod 8"); axs[1].set_ylabel("residual from linear fit (ns)")
    axs[1].set_title("remainder cost: deviation from linear time"); axs[1].legend(fontsize=7); axs[1].axhline(0, color="k", lw=.6)
    fig.tight_layout(); fig.savefig("figures/fig4_tail.png"); plt.close()
    out += ["\n## Tail (best ns/call, linear fit, residual by N mod 8)\n", pd.DataFrame(rows).to_markdown(index=False)]

s = load("stride")
if s is not None:
    s["label"] = np.where(s.kernel == "saxpy_gather", "gather-" + s.idx, "stride " + s.stride.astype(str))
    order = [f"stride {k}" for k in [1, 2, 4, 8, 16]] + ["gather-seq", "gather-rand"]
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.8))
    for ax, n in zip(axs, sorted(s.n.unique())):
        p = s[(s.n == n) & (s.dtype == "f32")].pivot(index="label", columns="variant", values="ns_per_elem").reindex(order)
        p.plot.bar(ax=ax, rot=30, color=[COL[c] for c in p.columns])
        ax.set_ylabel("ns per useful element"); ax.set_title(f"saxpy f32 stride/gather, N={n} elements processed")
    fig.tight_layout(); fig.savefig("figures/fig5_stride_gather.png"); plt.close()
    s["lines_per_elem"] = np.where(s.kernel == "saxpy_gather", np.nan,
                                   np.minimum(1.0, s.stride * np.where(s.dtype == "f32", 4, 8) / 64.0))
    out += ["\n## Stride / gather\n", s[["variant", "dtype", "n", "label", "ns_per_elem", "gibps", "lines_per_elem"]].round(4).to_markdown(index=False)]

if os.path.exists("results/raw/anomaly_mul.csv"):
    am = pd.read_csv("results/raw/anomaly_mul.csv")
    out += ["\n## mul f64 DRAM anomaly follow-up (ns/elem)\n",
            am.pivot_table(index="zskew", columns="variant", values="ns_per_elem", aggfunc=["median", "min", "max"]).round(3).to_markdown()]
open("results/processed/summary.md", "w").write("\n".join(out) + "\n")
print("figures:", sorted(glob.glob("figures/*.png")))
