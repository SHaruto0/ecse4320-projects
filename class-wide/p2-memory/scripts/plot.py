#!/usr/bin/env python3
"""Figures + processed tables for Project 2 from results/raw/*.csv.
Repeats are aggregated as median with min..max error bars."""
import json, os
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(ROOT)
os.makedirs("figures", exist_ok=True); os.makedirs("results/processed", exist_ok=True)
M = json.load(open("machine.json"))
GHZ = M["ghz"]
plt.rcParams.update({"figure.dpi": 130, "axes.grid": True, "grid.alpha": .3, "font.size": 9})
KiB, MiB, GiB = 1024, 1024 ** 2, 1024 ** 3
out = ["# Processed summary (auto-generated by scripts/plot.py)\n"]

def load(name):
    p = f"results/raw/{name}.csv"
    return pd.read_csv(p).fillna({"label": ""}) if os.path.exists(p) else None

def agg(d, keys, val):
    g = d.groupby(keys)[val].agg(["median", "min", "max", "count"]).reset_index()
    return g.rename(columns={"median": val})

def eb(g, val):
    return np.vstack([g[val] - g["min"], g["max"] - g[val]])

def cache_lines(ax, tlb=False):
    for kib, lab in [(M["l1d_kib"], "L1d"), (M["l2_kib"], "L2"), (M["l3_kib"], "LLC")]:
        ax.axvline(kib * KiB, color="k", ls=":", lw=.8)
        ax.text(kib * KiB, 0.98, f" {lab}", va="top", fontsize=7, transform=ax.get_xaxis_transform())

def human(b):
    for u, s in ((GiB, "GiB"), (MiB, "MiB"), (KiB, "KiB")):
        if b >= u: return f"{b / u:g} {s}"
    return f"{b} B"

# ---------- 1. working-set sweep + zero-queue baselines ----------
ws = load("ws")
lv = {}
if ws is not None:
    g = agg(ws, ["huge", "size"], "ns_per_step")
    fig, ax = plt.subplots(figsize=(8, 4.2))
    for huge, lab, c in ((1, "2 MiB huge pages", "#2ca02c"), (0, "4 KiB pages", "#d62728")):
        s = g[g.huge == huge]
        ax.errorbar(s["size"], s.ns_per_step, yerr=eb(s, "ns_per_step"), color=c, marker="o", ms=3, capsize=2, label=lab)
    ax.set_xscale("log", base=2); ax.set_yscale("log"); cache_lines(ax)
    ax.set_xlabel("working set (bytes)"); ax.set_ylabel("load-to-use latency (ns)")
    ax.set_title("Random pointer chase (64 B nodes): latency vs working set")
    ax.legend(); fig.tight_layout(); fig.savefig("figures/fig1_latency_vs_ws.png"); plt.close()
    h = g[g.huge == 1].set_index("size").ns_per_step
    def plateau(lo, hi):  # median latency of sizes in [lo, hi]
        v = h[(h.index >= lo) & (h.index <= hi)]
        return float(v.median()), int(v.index.min()), int(v.index.max())
    L1, L2, L3 = M["l1d_kib"] * KiB, M["l2_kib"] * KiB, M["l3_kib"] * KiB
    rows = []
    for name, lo, hi in (("L1d", 4 * KiB, L1 / 2), ("L2", L1 * 2, L2 / 2), ("L3 (LLC)", L2 * 2, L3 / 2),
                         ("DRAM", L3 * 8, h.index.max())):
        ns, a, b = plateau(lo, hi)
        lv[name] = ns
        rows.append(dict(level=name, sizes=f"{human(a)} - {human(b)}", latency_ns=round(ns, 2), cycles=round(ns * GHZ, 1)))
    dram4k = float(g[(g.huge == 0)].set_index("size").ns_per_step.loc[h.index.max()])
    rows.append(dict(level="DRAM, 4 KiB pages", sizes=human(h.index.max()), latency_ns=round(dram4k, 2), cycles=round(dram4k * GHZ, 1)))
    zq = pd.DataFrame(rows); zq.to_csv("results/processed/zero_queue.csv", index=False)
    out += [f"## Zero-queue latency (huge pages, plateau medians; cycles at {GHZ} GHz)\n", zq.to_markdown(index=False),
            f"\nImplied clock if L1 load-to-use = 5 cycles: {5 / lv['L1d']:.2f} GHz\n"]

# ---------- 2. pattern / granularity ----------
pl, pb = load("pattern_lat"), load("pattern_bw")
if pl is not None and pb is not None:
    gl = agg(pl, ["pattern", "stride"], "ns_per_step")
    pb["cfg"] = np.where(pb.pattern == "seq", "seq stride " + pb.stride.astype(str), "rand gran " + pb.gran.astype(str))
    gb = agg(pb, ["label", "cfg", "pattern", "gran", "stride"], "useful_gbps")
    gb2 = agg(pb, ["label", "cfg"], "line_gbps")
    fig, axs = plt.subplots(1, 2, figsize=(11, 4))
    for i, pat in enumerate(("seq", "rand")):
        s = gl[gl.pattern == pat]
        axs[0].bar(np.arange(len(s)) + i * 0.4, s.ns_per_step, 0.4, yerr=eb(s, "ns_per_step"), capsize=2, label=pat)
    axs[0].set_xticks(np.arange(3) + 0.2, [f"{x} B" for x in sorted(gl.stride.unique())]); axs[0].set_yscale("log")
    axs[0].set_xlabel("node spacing (stride)"); axs[0].set_ylabel("ns per access"); axs[0].legend()
    axs[0].set_title(f"Pointer-chase latency, {human(int(pl['size'].iloc[0]))}")
    order = [f"seq stride {s}" for s in (64, 128, 256, 1024, 4096)] + [f"rand gran {g}" for g in (64, 256, 1024, 4096)]
    for i, lab in enumerate(("1T", "allT")):
        s = gb[gb.label == lab].set_index("cfg").reindex(order).dropna()
        axs[1].bar(np.arange(len(s)) + i * 0.4, s.useful_gbps, 0.4, yerr=[s.useful_gbps - s["min"], s["max"] - s.useful_gbps],
                   capsize=2, label={"1T": "1 thread", "allT": "all threads"}[lab])
    axs[1].set_xticks(np.arange(len(order)) + 0.2, order, rotation=35, ha="right")
    axs[1].set_ylabel("useful GB/s (bytes actually read)"); axs[1].legend(); axs[1].set_title("Read bandwidth vs pattern / granularity")
    fig.tight_layout(); fig.savefig("figures/fig2_pattern_granularity.png"); plt.close()
    t = gb.merge(gb2[["label", "cfg", "line_gbps"]], on=["label", "cfg"])
    out += ["\n## Pattern latency (ns/access)\n", gl.round(2).to_markdown(index=False),
            "\n## Pattern bandwidth (GB/s; useful = bytes the program read, line = 64B lines touched)\n",
            t[["label", "cfg", "useful_gbps", "min", "max", "line_gbps"]].round(2).to_markdown(index=False)]

# ---------- 3. read/write mix ----------
mb, ml = load("mix_bw"), load("mix_loaded")
if mb is not None:
    gm = agg(mb, ["label", "read_pct"], "useful_gbps")
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.6))
    order = [100, 70, 50, 0]
    for i, lab in enumerate(("1T", "allT")):
        s = gm[gm.label == lab].set_index("read_pct").reindex(order)
        axs[0].bar(np.arange(4) + i * 0.4, s.useful_gbps, 0.4, yerr=[s.useful_gbps - s["min"], s["max"] - s.useful_gbps], capsize=2,
                   label={"1T": "1 thread", "allT": "all threads"}[lab])
    axs[0].set_xticks(np.arange(4) + 0.2, [f"{r}R/{100 - r}W" for r in order]); axs[0].set_ylabel("GB/s (program bytes)")
    axs[0].set_title("Sequential bandwidth vs read/write mix"); axs[0].legend()
    rows = gm.copy()
    if ml is not None:
        gl_ = agg(ml, ["read_pct"], "lat_ns").set_index("read_pct").reindex(order)
        gbw = agg(ml, ["read_pct"], "load_gbps").set_index("read_pct").reindex(order)
        axs[1].bar(range(4), gl_.lat_ns, yerr=[gl_.lat_ns - gl_["min"], gl_["max"] - gl_.lat_ns], capsize=2, color="#9467bd")
        for i, (l, b) in enumerate(zip(gl_.lat_ns, gbw.load_gbps)):
            axs[1].text(i, l, f"{b:.1f} GB/s\nload", ha="center", va="bottom", fontsize=7)
        if "DRAM" in lv: axs[1].axhline(lv["DRAM"], color="k", ls="--", lw=.8, label="idle DRAM latency"); axs[1].legend(fontsize=7)
        axs[1].set_xticks(range(4), [f"{r}R/{100 - r}W" for r in order]); axs[1].set_ylabel("chaser latency (ns)")
        axs[1].set_title("Loaded latency (all other cores loading)")
        out += ["\n## Loaded latency by mix\n", pd.concat([gl_.lat_ns, gbw.load_gbps], axis=1).round(2).to_markdown()]
    fig.tight_layout(); fig.savefig("figures/fig3_rw_mix.png"); plt.close()
    out += ["\n## Bandwidth by mix (GB/s)\n", gm.round(2).to_markdown(index=False)]

# ---------- 4. intensity: throughput vs latency, knee, Little's law ----------
mlp, lt, ld = load("mlp"), load("loaded_threads"), load("loaded_delay")
fig, axs = plt.subplots(1, 2, figsize=(11, 4.2))
if mlp is not None:
    g = mlp.groupby("chains").agg(ns=("ns_per_step", "median"), gbps=("gbps", "median"), lo=("gbps", "min"), hi=("gbps", "max")).reset_index()
    g["little_N"] = g.gbps * g.ns / 64          # outstanding lines = throughput x latency
    axs[0].errorbar(g.gbps, g.ns, xerr=[g.gbps - g.lo, g.hi - g.gbps], marker="o", capsize=2, color="#1f77b4")
    for _, r in g.iterrows(): axs[0].annotate(f"K={int(r.chains)}", (r.gbps, r.ns), fontsize=7, xytext=(3, 3), textcoords="offset points")
    # knee: first K where adding chains gives < 10% more throughput
    knee = int(g.chains[g.gbps.idxmax()])   # beyond this, more outstanding misses add latency, not throughput
    axs[0].set_xlabel("achieved bandwidth (GB/s, 64 B per access)"); axs[0].set_ylabel("latency per access (ns)")
    axs[0].set_title(f"1 core, K independent chases (knee ~K={knee})")
    g.round(3).to_csv("results/processed/mlp.csv", index=False)
    out += [f"\n## Single-core MLP sweep (knee at K = {knee})\n", g.round(3).to_markdown(index=False)]
for d, lab, key, c in ((lt, "vary # loader threads", "nload", "#2ca02c"), (ld, "all loaders, vary delay", "delay", "#d62728")):
    if d is None: continue
    g = d.groupby(key).agg(lat=("lat_ns", "median"), bw=("total_gbps", "median"), lo=("lat_ns", "min"), hi=("lat_ns", "max")).reset_index().sort_values("bw")
    g["little_N"] = g.bw * g.lat / 64
    axs[1].errorbar(g.bw, g.lat, yerr=[g.lat - g.lo, g.hi - g.lat], marker="o", capsize=2, color=c, label=lab)
    for _, r in g.iterrows(): axs[1].annotate(f"{int(r[key])}", (r.bw, r.lat), fontsize=6, xytext=(2, 2), textcoords="offset points")
    out += [f"\n## Loaded latency, {lab}\n", g.round(3).to_markdown(index=False)]
    g.round(3).to_csv(f"results/processed/loaded_{key}.csv", index=False)
axs[1].set_xlabel("total memory bandwidth (GB/s)"); axs[1].set_ylabel("chaser latency (ns)")
axs[1].set_title("Throughput-latency curve (labels = threads / delay)"); axs[1].legend(fontsize=7)
fig.tight_layout(); fig.savefig("figures/fig4_throughput_latency.png"); plt.close()

# ---------- 5. TLB ----------
tl, tc = load("tlb"), load("tlbconflict")
if tl is not None:
    g = agg(tl, ["huge", "size"], "ns_per_step"); g["pages"] = g["size"] // 4096
    fig, axs = plt.subplots(1, 2 if tc is not None else 1, figsize=(12 if tc is not None else 8, 4), squeeze=False)
    ax = axs[0][0]
    for huge, lab, c in ((0, "4 KiB pages", "#d62728"), (1, "2 MiB huge pages", "#2ca02c")):
        s_ = g[g.huge == huge]
        ax.errorbar(s_["size"], s_.ns_per_step, yerr=eb(s_, "ns_per_step"), marker="o", ms=3, capsize=2, color=c, label=lab)
    for ent, lab in ((M.get("dtlb_entries_4k"), "L1 DTLB reach (4K)"), (M.get("stlb_entries"), "STLB reach (4K)")):
        if ent: ax.axvline(ent * 4096, color="#d62728", ls=":", lw=.8); ax.text(ent * 4096, .02, f" {lab}", fontsize=7, rotation=90, transform=ax.get_xaxis_transform(), color="#d62728")
    ax.set_xscale("log", base=2); ax.set_yscale("log")
    ax.set_xlabel("virtual footprint (one 64 B line per 4 KiB page)"); ax.set_ylabel("ns per access")
    ax.set_title("TLB impact: page-stride random chase"); ax.legend()
    if tc is not None:
        gc = agg(tc, ["huge", "size"], "ns_per_step"); ax2 = axs[0][1]
        for huge, lab, c in ((0, "4 KiB pages", "#d62728"), (1, "2 MiB huge pages", "#2ca02c")):
            s_ = gc[gc.huge == huge]; s2 = g[g.huge == huge]
            ax2.errorbar(s_["size"], s_.ns_per_step, yerr=eb(s_, "ns_per_step"), marker="s", ms=3, capsize=2, color=c, label=f"{lab}, v1 placement")
            ax2.plot(s2["size"], s2.ns_per_step, color=c, ls=":", lw=1, label=f"{lab}, fixed placement")
        ax2.set_xscale("log", base=2); ax2.set_yscale("log"); ax2.legend(fontsize=7)
        ax2.set_xlabel("virtual footprint"); ax2.set_title("Pitfall 2: line offset cycling through 64 values -> set conflicts")
        pc = gc.pivot(index="size", columns="huge", values="ns_per_step").rename(columns={0: "v1_4k", 1: "v1_huge"})
        pc.index = [human(x) for x in pc.index]
        out += ["\n## Set-conflict demo (v1 per-page placement, ns/access)\n", pc.round(2).to_markdown()]
    fig.tight_layout(); fig.savefig("figures/fig5_tlb.png"); plt.close()
    p = g.pivot(index="size", columns="huge", values="ns_per_step").rename(columns={0: "ns_4k", 1: "ns_huge"})
    p["tlb_penalty_ns"] = p.ns_4k - p.ns_huge; p["pages"] = p.index // 4096
    p.index = [human(x) for x in p.index]
    out += ["\n## TLB sweep (ns/access)\n", p.round(2).to_markdown()]

# ---------- 6. cache-miss impact + AMAT model ----------
kn = load("kern")
if kn is not None and lv:
    g = agg(kn, ["pattern", "size"], "ns_per_elem")
    fig, ax = plt.subplots(figsize=(8, 4.2))
    for pat, c in (("seq", "#1f77b4"), ("rand", "#d62728")):
        s = g[g.pattern == pat]
        ax.errorbar(s["size"], s.ns_per_elem, yerr=eb(s, "ns_per_elem"), marker="o", ms=3, capsize=2, color=c, label=f"saxpy {pat} index")
    # AMAT model for random access: P(hit level) from capacity ratios, latencies from the chase plateaus
    caps = [M["l1d_kib"] * KiB, M["l2_kib"] * KiB, M["l3_kib"] * KiB]
    lat = [lv["L1d"], lv["L2"], lv["L3 (LLC)"], lv["DRAM"]]
    xs = np.array(sorted(g["size"].unique()), float)
    def amat(w):
        p_in = [min(1.0, c / w) for c in caps] + [1.0]
        p = [p_in[0]] + [p_in[i] - p_in[i - 1] for i in range(1, 4)]
        return sum(pi * li for pi, li in zip(p, lat)), p
    model = np.array([2 * amat(w)[0] for w in xs])   # x[j] and y[j]: two random lines per element
    ax.plot(xs, model, "k--", lw=1, label="2 x AMAT (serialized, no overlap)")
    ax.set_xscale("log", base=2); ax.set_yscale("log"); cache_lines(ax)
    ax.set_xlabel("footprint of x + y (bytes)"); ax.set_ylabel("ns per element")
    ax.set_title("Cache-miss impact: same work, different locality"); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig("figures/fig6_cache_miss_impact.png"); plt.close()
    r = g[g.pattern == "rand"].copy(); r["amat_ns"] = [amat(w)[0] for w in r["size"]]
    r["implied_mlp"] = 2 * r.amat_ns / r.ns_per_elem   # overlapped misses the OoO core sustained
    r["p_dram"] = [amat(w)[1][3] for w in r["size"]]
    counters = kn.drop(columns=["rep", "label", "mode"]).groupby(["pattern", "size"]).median(numeric_only=True)
    has_ctr = counters["cycles"].notna().any() if "cycles" in counters else False
    out += ["\n## Cache-miss impact (rand pattern vs AMAT model)\n", r[["size", "ns_per_elem", "amat_ns", "p_dram", "implied_mlp"]].round(3).to_markdown(index=False),
            "\n## Seq pattern\n", g[g.pattern == "seq"][["size", "ns_per_elem"]].round(3).to_markdown(index=False),
            f"\nHardware counters available: {has_ctr}\n"]
    if has_ctr: out += [counters.round(4).to_markdown()]

# ---------- 7. pitfall ----------
pf = load("pitfall")
if pf is not None:
    g = agg(pf, ["label"], "ns_per_step")
    order = list(dict.fromkeys(pf.label))
    g = g.set_index("label").reindex(order)
    fig, ax = plt.subplots(figsize=(8, 3.4))
    cols = ["#ff7f0e", "#ff7f0e", "#ff7f0e", "#2ca02c"]
    ax.barh(range(len(g)), g.ns_per_step, xerr=[g.ns_per_step - g["min"], g["max"] - g.ns_per_step], color=cols[:len(g)], capsize=2)
    ax.set_yticks(range(len(g)), g.index, fontsize=8); ax.invert_yaxis(); ax.set_xlabel("measured 'DRAM latency' (ns)")
    for i, v in enumerate(g.ns_per_step): ax.text(v, i, f" {v:.1f}", va="center", fontsize=8)
    ax.set_title("Benchmark pitfall: three of these are not DRAM latency")
    fig.tight_layout(); fig.savefig("figures/fig7_pitfall.png"); plt.close()
    out += ["\n## Pitfall\n", g[["ns_per_step", "min", "max"]].round(2).to_markdown()]

open("results/processed/summary.md", "w").write("\n".join(out) + "\n")
print("figures:", sorted(os.listdir("figures")))
