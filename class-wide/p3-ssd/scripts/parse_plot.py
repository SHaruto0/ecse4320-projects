#!/usr/bin/env python3
"""Parse fio JSON (results/raw/**) -> results/processed/*.csv + summary.md, and make figures/.
Latency = fio total latency (lat_ns = submission + completion). Repeats: median, min..max."""
import glob, json, os, re
import numpy as np, pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(ROOT)
os.makedirs("figures", exist_ok=True); os.makedirs("results/processed", exist_ok=True)
plt.rcParams.update({"figure.dpi": 130, "axes.grid": True, "grid.alpha": .3, "font.size": 9})
P = {"p50": "50.000000", "p90": "90.000000", "p95": "95.000000", "p99": "99.000000", "p99.9": "99.900000", "p99.99": "99.990000"}

rows = []
for f in sorted(glob.glob("results/raw/*/*.json")):
    exp = f.split("/")[2]
    name, rep = re.match(r"(.*)__rep(\d+)\.json", os.path.basename(f)).groups()
    try:
        d = json.load(open(f))
    except Exception:
        continue
    j = d["jobs"][0]
    o = j["job options"] if "job options" in j else {}
    row = dict(exp=exp, name=name, rep=int(rep), bs=o.get("bs", ""), iodepth=int(o.get("iodepth", 1)),
               numjobs=int(o.get("numjobs", 1)), usr_cpu=j["usr_cpu"], sys_cpu=j["sys_cpu"],
               util=(d.get("disk_util") or [{}])[0].get("util", np.nan))
    tot_iops = tot_bw = 0
    for side in ("read", "write"):
        s = j[side]
        if s["total_ios"] == 0: continue
        tot_iops += s["iops"]; tot_bw += s["bw_bytes"]
        pct = s["lat_ns"].get("percentile", {})
        row[f"{side}_iops"] = s["iops"]; row[f"{side}_MBps"] = s["bw_bytes"] / 1e6
        row[f"{side}_lat_mean_us"] = s["lat_ns"]["mean"] / 1e3
        for k, v in P.items(): row[f"{side}_{k}_us"] = pct.get(v, np.nan) / 1e3
    row["iops"], row["MBps"] = tot_iops, tot_bw / 1e6
    # mean latency weighted by ops, for mixes
    lr, lw = row.get("read_lat_mean_us", 0), row.get("write_lat_mean_us", 0)
    ir, iw = row.get("read_iops", 0), row.get("write_iops", 0)
    row["lat_mean_us"] = (lr * ir + lw * iw) / (ir + iw) if ir + iw else np.nan
    rows.append(row)
df = pd.DataFrame(rows)
df.to_csv("results/processed/all_runs.csv", index=False)

def agg(d, cols):
    g = d.groupby("name")
    out = g[cols].median()
    for c in cols:
        out[c + "_min"], out[c + "_max"] = g[c].min(), g[c].max()
    out["n"] = g.size()
    return out

def yerr(a, c):
    return np.vstack([a[c] - a[c + "_min"], a[c + "_max"] - a[c]])

def bsbytes(s):
    s = s.lower(); m = {"k": 1024, "m": 1024 ** 2, "g": 1024 ** 3}
    return int(float(s[:-1]) * m[s[-1]]) if s[-1] in m else int(s)

out = ["# Processed summary (auto-generated by scripts/parse_plot.py)\n",
       "Latency = fio total latency (submission + completion), microseconds. Values are medians of repeats.\n"]

# ---------- 1. QD=1 baselines ----------
q1 = df[df.exp == "qd1"]
if len(q1):
    t = []
    for name in ("randread_4k", "randwrite_4k", "seqread_128k", "seqwrite_128k"):
        s = q1[q1.name == name]
        if not len(s): continue
        side = "write" if "write" in name else "read"
        t.append({"workload": name, "IOPS": s.iops.median(), "MB/s": s.MBps.median(),
                  "mean": s[f"{side}_lat_mean_us"].median(), "p50": s[f"{side}_p50_us"].median(),
                  "p95": s[f"{side}_p95_us"].median(), "p99": s[f"{side}_p99_us"].median(),
                  "p99.9": s[f"{side}_p99.9_us"].median(),
                  "mean range": f"{s[f'{side}_lat_mean_us'].min():.1f}-{s[f'{side}_lat_mean_us'].max():.1f}"})
    t = pd.DataFrame(t); t.to_csv("results/processed/qd1.csv", index=False)
    out += ["## QD=1 baselines (latency in us)\n", t.round(1).to_markdown(index=False)]
    fig, ax = plt.subplots(figsize=(7, 3.6))
    x = np.arange(len(t)); w = 0.2
    for i, k in enumerate(("p50", "p95", "p99", "p99.9")):
        ax.bar(x + (i - 1.5) * w, t[k], w, label=k)
    ax.set_xticks(x, t.workload); ax.set_yscale("log"); ax.set_ylabel("latency (us)")
    ax.set_title("QD=1 latency percentiles (direct I/O)"); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig("figures/fig1_qd1_latency.png"); plt.close()

# ---------- 2. block-size sweep ----------
b = df[df.exp == "bs"].copy()
if len(b):
    b["pattern"] = np.where(b.name.str.startswith("rand"), "random", "sequential")
    a = agg(b, ["MBps", "iops", "read_lat_mean_us", "read_p99_us"]).reset_index()
    a["pattern"] = np.where(a.name.str.startswith("rand"), "random", "sequential")
    a["bs"] = a.name.str.split("_").str[-1]; a["bytes"] = a.bs.map(bsbytes); a = a.sort_values(["pattern", "bytes"])
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.8))
    for pat, c in (("random", "#d62728"), ("sequential", "#1f77b4")):
        s = a[a.pattern == pat]
        axs[0].errorbar(s.bytes, s.MBps, yerr=yerr(s, "MBps"), marker="o", color=c, capsize=2, label=f"{pat} MB/s")
        ax2 = axs[0].twinx() if pat == "random" else ax2
        ax2.plot(s.bytes, s.iops / 1e3, ls=":", marker="x", color=c, label=f"{pat} kIOPS")
        axs[1].errorbar(s.bytes, s.read_lat_mean_us, yerr=yerr(s, "read_lat_mean_us"), marker="o", color=c, capsize=2, label=f"{pat} mean")
        axs[1].plot(s.bytes, s.read_p99_us, ls="--", marker="^", color=c, label=f"{pat} p99")
    for ax in axs: ax.set_xscale("log", base=2); ax.set_xticks(a.bytes.unique(), [x for x in a.drop_duplicates("bytes").bs]); ax.set_xlabel("block size")
    axs[0].set_ylabel("MB/s (solid)"); ax2.set_ylabel("kIOPS (dotted)"); axs[0].legend(loc="upper left", fontsize=7); ax2.legend(loc="center right", fontsize=7)
    axs[0].set_title("Read throughput vs block size (QD=32)")
    axs[1].set_yscale("log"); axs[1].set_ylabel("latency (us)"); axs[1].legend(fontsize=7); axs[1].set_title("Latency from the same runs")
    fig.tight_layout(); fig.savefig("figures/fig2_blocksize.png"); plt.close()
    a.round(1).to_csv("results/processed/blocksize.csv", index=False)
    out += ["\n## Block-size sweep (read, QD=32)\n", a[["pattern", "bs", "iops", "MBps", "MBps_min", "MBps_max", "read_lat_mean_us", "read_p99_us"]].round(1).to_markdown(index=False)]

# ---------- 3. read/write mix ----------
m = df[df.exp == "mix"].copy()
if len(m):
    cols = ["iops", "MBps", "read_iops", "write_iops", "read_lat_mean_us", "write_lat_mean_us", "read_p99_us", "write_p99_us"]
    for c in cols:
        if c not in m: m[c] = np.nan
    a = agg(m, cols).reset_index(); a["read_pct"] = a.name.str.extract(r"r(\d+)").astype(int)
    a = a.sort_values("read_pct", ascending=False)
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.6)); lab = [f"{r}R/{100 - r}W" for r in a.read_pct]
    axs[0].bar(lab, a.iops / 1e3, yerr=yerr(a, "iops") / 1e3, capsize=2, color="#9467bd"); axs[0].set_ylabel("total kIOPS")
    axs[0].set_title("4 KiB random, QD=32: throughput vs mix")
    x = np.arange(len(a))
    axs[1].bar(x - 0.2, a.read_lat_mean_us, 0.4, label="read mean"); axs[1].bar(x + 0.2, a.write_lat_mean_us, 0.4, label="write mean")
    axs[1].plot(x - 0.2, a.read_p99_us, "k^", ms=4, label="read p99"); axs[1].plot(x + 0.2, a.write_p99_us, "kv", ms=4, label="write p99")
    axs[1].set_xticks(x, lab); axs[1].set_yscale("log"); axs[1].set_ylabel("latency (us)"); axs[1].legend(fontsize=7)
    axs[1].set_title("Per-direction latency")
    fig.tight_layout(); fig.savefig("figures/fig3_rw_mix.png"); plt.close()
    out += ["\n## Read/write mix (4 KiB random, QD=32)\n", a[["read_pct"] + cols].round(1).to_markdown(index=False)]

# ---------- 4. QD sweep + Little's law + 5. tails ----------
q = df[df.exp == "qd"].copy()
if len(q):
    q["outstanding"] = q.iodepth * q.numjobs
    a = agg(q, ["iops", "read_lat_mean_us", "read_p50_us", "read_p95_us", "read_p99_us", "read_p99.9_us", "usr_cpu", "sys_cpu"]).reset_index()
    a = a.merge(q.groupby("name").outstanding.first(), on="name").sort_values("outstanding")
    a["little_N"] = a.iops * a.read_lat_mean_us / 1e6       # N = X * R
    a["series"] = np.where(a.name.str.contains("jobs"), "jobs", "qd")
    one = a[a.series == "qd"]; mj = a[a.series == "jobs"]
    # knee on the single-job iodepth curve: smallest QD reaching >= 90% of that curve's max IOPS
    knee = one[one.iops >= 0.9 * one.iops.max()].iloc[0]
    fig, ax = plt.subplots(figsize=(7.5, 4.4))
    ax.errorbar(one.iops / 1e3, one.read_lat_mean_us, xerr=yerr(one, "iops") / 1e3, marker="o", capsize=2, color="#1f77b4", label="1 job, iodepth 1..256: mean")
    ax.plot(one.iops / 1e3, one.read_p99_us, "--^", color="#1f77b4", alpha=.6, label="1 job: p99")
    if len(mj):
        mj2 = pd.concat([one[one.outstanding == 32], mj]).sort_values("outstanding")
        ax.errorbar(mj2.iops / 1e3, mj2.read_lat_mean_us, xerr=yerr(mj2, "iops") / 1e3, marker="s", capsize=2, color="#d62728", label="iodepth 32 x 1..8 jobs: mean")
        ax.plot(mj2.iops / 1e3, mj2.read_p99_us, "--v", color="#d62728", alpha=.6, label="jobs: p99")
    for _, r in a.iterrows():
        ax.annotate(f"QD{int(r.outstanding)}" if r.series == "qd" else f"{int(r.outstanding)}j",
                    (r.iops / 1e3, r.read_lat_mean_us), fontsize=7, xytext=(3, 3), textcoords="offset points")
    ax.axvline(knee.iops / 1e3, color="k", ls=":", lw=.8)
    ax.text(knee.iops / 1e3, .9, f" knee (1 job) ~QD{int(knee.outstanding)}", fontsize=8, transform=ax.get_xaxis_transform())
    ax.set_yscale("log"); ax.set_xlabel("throughput (kIOPS, 4 KiB random read)"); ax.set_ylabel("latency (us)")
    ax.set_title("Throughput vs latency as outstanding I/Os grow"); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig("figures/fig4_qd_knee.png"); plt.close()
    fig, ax = plt.subplots(figsize=(7.5, 4))
    for k, c in (("read_p50_us", "p50"), ("read_p95_us", "p95"), ("read_p99_us", "p99"), ("read_p99.9_us", "p99.9")):
        ax.plot(one.outstanding, one[k], marker="o", label=c)
    ax.set_xscale("log", base=2); ax.set_yscale("log"); ax.set_xlabel("outstanding I/Os (iodepth x jobs)"); ax.set_ylabel("latency (us)")
    ax.set_title("Tail latency vs iodepth (1 job, 4 KiB random read)"); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig("figures/fig5_tail.png"); plt.close()
    a.round(2).to_csv("results/processed/qd_sweep.csv", index=False)
    out += [f"\n## QD sweep (4 KiB random read). Knee (1-job curve, first point >= 90% of its max IOPS): QD {int(knee.outstanding)}\n",
            a[["name", "outstanding", "iops", "iops_min", "iops_max", "read_lat_mean_us", "read_p50_us", "read_p95_us", "read_p99_us", "read_p99.9_us", "little_N", "usr_cpu", "sys_cpu"]].round(1).to_markdown(index=False)]

# ---------- 6. working set / LBA range ----------
w = df[df.exp == "ws"].copy()
if len(w):
    a = agg(w, ["iops", "read_lat_mean_us", "read_p99_us"]).reset_index()
    a["range"] = a.name.str.extract(r"range(\w+)$"); a["bytes"] = a.range.map(bsbytes); a = a.sort_values("bytes")
    out += ["\n## LBA range (4 KiB random read, QD=32)\n", a[["range", "iops", "iops_min", "iops_max", "read_lat_mean_us", "read_p99_us"]].round(1).to_markdown(index=False)]
    ws_tab = a

# ---------- 7. device state ----------
logf = sorted(glob.glob("results/raw/state/sustained_bw*.log"))
if logf:
    L = pd.read_csv(logf[0], header=None, usecols=[0, 1], names=["ms", "KiBps"])
    L["s"] = L.ms / 1000; L["MBps"] = L.KiBps * 1024 / 1e6
    fig, axs = plt.subplots(1, 2 if len(w) else 1, figsize=(11 if len(w) else 7, 3.6), squeeze=False)
    ax = axs[0][0]
    ax.plot(L.s, L.MBps, lw=.8, color="#d62728"); ax.plot(L.s, L.MBps.rolling(10, min_periods=1).median(), color="k", lw=1.2, label="10 s rolling median")
    ax.set_xlabel("time (s)"); ax.set_ylabel("MB/s"); ax.set_title("Sustained 4 KiB random write, QD=32"); ax.legend(fontsize=7)
    if len(w):
        ax = axs[0][1]
        ax.errorbar(ws_tab.bytes, ws_tab.iops / 1e3, yerr=yerr(ws_tab, "iops") / 1e3, marker="o", capsize=2)
        ax.set_xscale("log", base=2); ax.set_xticks(ws_tab.bytes, ws_tab.range); ax.set_xlabel("LBA range (test-file span)")
        ax.set_ylabel("kIOPS"); ax.set_title("4 KiB random read vs LBA range (QD=32)")
    fig.tight_layout(); fig.savefig("figures/fig6_state_range.png"); plt.close()
    n = len(L); first, last = L.MBps.iloc[: max(1, n // 6)].median(), L.MBps.iloc[-max(1, n // 6):].median()
    out += [f"\n## Sustained write ({L.s.max():.0f} s): first-sixth median {first:.1f} MB/s, last-sixth median {last:.1f} MB/s, "
            f"min {L.MBps.min():.1f}, max {L.MBps.max():.1f}, CoV {L.MBps.std() / L.MBps.mean():.2f}\n"]

# ---------- 8. pitfall ----------
p = df[df.exp == "pitfall"]
if len(p):
    a = agg(p, ["iops", "read_lat_mean_us", "read_p99_us"]).reset_index()
    order = ["buffered_randread_4k_256m", "buffered_warm_randread_4k_256m", "direct_randread_4k_256m", "psync_iodepth32_randread_4k", "libaio_iodepth32_randread_4k"]
    a = a.set_index("name").reindex([o for o in order if o in set(a.name)]).reset_index()
    COLS = {"buffered_randread_4k_256m": "#ffbb78", "buffered_warm_randread_4k_256m": "#ff7f0e", "psync_iodepth32_randread_4k": "#ff7f0e"}
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.6))
    axs[0].barh(a.name, a.iops / 1e3, xerr=yerr(a, "iops") / 1e3, color=[COLS.get(n, "#2ca02c") for n in a.name], capsize=2)
    axs[0].set_xscale("log"); axs[0].set_xlabel("kIOPS"); axs[0].invert_yaxis(); axs[0].set_title("Misleading (orange) vs correct (green)")
    axs[1].barh(a.name, a.read_lat_mean_us, color=[COLS.get(n, "#2ca02c") for n in a.name])
    axs[1].set_xscale("log"); axs[1].set_xlabel("mean latency (us)"); axs[1].invert_yaxis(); axs[1].set_yticks([])
    fig.tight_layout(); fig.savefig("figures/fig7_pitfall.png"); plt.close()
    out += ["\n## Pitfalls\n", a[["name", "iops", "iops_min", "iops_max", "read_lat_mean_us", "read_p99_us"]].round(1).to_markdown(index=False)]

open("results/processed/summary.md", "w").write("\n".join(out) + "\n")
print("figures:", sorted(os.listdir("figures")))
